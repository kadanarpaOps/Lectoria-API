CREATE TABLE IF NOT EXISTS T_GENRES (
    GENRE_ID UUID PRIMARY KEY,
    GENRE_NAME VARCHAR(50) NOT NULL UNIQUE,
    GENRE_CREATED_AT TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    GENRE_UPDATED_AT TIMESTAMP WITHOUT TIME ZONE
);

CREATE TABLE IF NOT EXISTS T_TAGS (
    TAG_ID UUID PRIMARY KEY,
    TAG_NAME VARCHAR(100) NOT NULL UNIQUE,
    TAG_CREATED_AT TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    TAG_UPDATED_AT TIMESTAMP WITHOUT TIME ZONE
);

CREATE TABLE IF NOT EXISTS T_STORIES (
    STORY_ID UUID PRIMARY KEY,
    STORY_TITLE VARCHAR(120) NOT NULL UNIQUE,
    STORY_COVER_URL TEXT NOT NULL DEFAULT '',
    STORY_COVER_PUBLIC_ID TEXT,
    STORY_DESCRIPTION TEXT NOT NULL,
    STORY_SUPPORTS_NSFW BOOLEAN NOT NULL DEFAULT FALSE,
    STORY_TOTAL_RATING NUMERIC(4,2) NOT NULL DEFAULT 0,
    STORY_RATING_SUM NUMERIC(10,2) NOT NULL DEFAULT 0,
    STORY_RATING_COUNT INTEGER NOT NULL DEFAULT 0,
    STORY_TOTAL_CHAPTERS INTEGER NOT NULL DEFAULT 0,
    STORY_HIDDEN BOOLEAN NOT NULL DEFAULT TRUE,
    STORY_STATUS VARCHAR(20) NOT NULL DEFAULT 'IN_PROGRESS'
        CHECK (STORY_STATUS IN ('IN_PROGRESS', 'COMPLETED', 'ABANDONED', 'PAUSED')),
    STORY_TOTAL_VIEWS INTEGER NOT NULL DEFAULT 0,
    USER_ID UUID NOT NULL,
    STORY_TOTAL_FAVORITES INTEGER NOT NULL DEFAULT 0,
    STORY_TOTAL_COMMENTS INTEGER NOT NULL DEFAULT 0,
    GENRE_ID UUID NOT NULL REFERENCES T_GENRES(GENRE_ID),
    SECONDARY_GENRE_ID UUID REFERENCES T_GENRES(GENRE_ID),
    STORY_CREATED_AT TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    STORY_UPDATED_AT TIMESTAMP WITHOUT TIME ZONE,
    STORY_LAST_ACTIVITY_AT TIMESTAMP WITHOUT TIME ZONE
);
CREATE INDEX IF NOT EXISTS IDX_STORIES_USER ON T_STORIES(USER_ID);
CREATE INDEX IF NOT EXISTS IDX_STORIES_GENRE ON T_STORIES(GENRE_ID);

CREATE TABLE IF NOT EXISTS T_STORY_TAGS (
    STORY_ID UUID NOT NULL REFERENCES T_STORIES(STORY_ID) ON DELETE CASCADE,
    TAG_ID UUID NOT NULL REFERENCES T_TAGS(TAG_ID) ON DELETE CASCADE,
    PRIMARY KEY (STORY_ID, TAG_ID)
);

CREATE TABLE IF NOT EXISTS T_CHAPTERS (
    CHAPTER_ID UUID PRIMARY KEY,
    CHAPTER_TITLE TEXT NOT NULL,
    CHAPTER_ORDER INTEGER NOT NULL,
    CHAPTER_CONTENT TEXT NOT NULL,
    CHAPTER_HIDDEN BOOLEAN NOT NULL DEFAULT TRUE,
    CHAPTER_TOTAL_COMMENTS INTEGER NOT NULL DEFAULT 0,
    STORY_ID UUID NOT NULL REFERENCES T_STORIES(STORY_ID) ON DELETE CASCADE,
    CHAPTER_CREATED_AT TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHAPTER_UPDATED_AT TIMESTAMP WITHOUT TIME ZONE,
    CHAPTER_LAST_ACTIVITY_AT TIMESTAMP WITHOUT TIME ZONE,
    UNIQUE (STORY_ID, CHAPTER_ORDER)
);
CREATE INDEX IF NOT EXISTS IDX_CHAPTERS_STORY ON T_CHAPTERS(STORY_ID, CHAPTER_ORDER);

CREATE TABLE IF NOT EXISTS T_COMMENTS (
    COMMENT_ID UUID PRIMARY KEY,
    COMMENT_USERNAME VARCHAR(120) NOT NULL,
    USER_ID VARCHAR(100) NOT NULL,
    COMMENT_CONTENT TEXT NOT NULL,
    COMMENT_LIKES INTEGER NOT NULL DEFAULT 0,
    STORY_ID UUID REFERENCES T_STORIES(STORY_ID) ON DELETE CASCADE,
    CHAPTER_ID UUID REFERENCES T_CHAPTERS(CHAPTER_ID) ON DELETE CASCADE,
    COMMENT_CREATED_AT TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    COMMENT_UPDATED_AT TIMESTAMP WITHOUT TIME ZONE,
    CHECK (STORY_ID IS NOT NULL OR CHAPTER_ID IS NOT NULL)
);
CREATE INDEX IF NOT EXISTS IDX_COMMENTS_STORY ON T_COMMENTS(STORY_ID, COMMENT_CREATED_AT);
CREATE INDEX IF NOT EXISTS IDX_COMMENTS_CHAPTER ON T_COMMENTS(CHAPTER_ID, COMMENT_CREATED_AT);

CREATE TABLE IF NOT EXISTS T_COMMENT_LIKES (
    COMMENT_LIKE_ID UUID PRIMARY KEY,
    COMMENT_ID UUID NOT NULL REFERENCES T_COMMENTS(COMMENT_ID) ON DELETE CASCADE,
    USER_ID UUID NOT NULL,
    COMMENT_LIKE_CREATED_AT TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (COMMENT_ID, USER_ID)
);

CREATE TABLE IF NOT EXISTS T_RATINGS (
    RATING_ID UUID PRIMARY KEY,
    STORY_ID UUID NOT NULL REFERENCES T_STORIES(STORY_ID) ON DELETE CASCADE,
    USER_ID UUID NOT NULL,
    RATING_SCORE NUMERIC(4,2) NOT NULL CHECK (RATING_SCORE >= 0 AND RATING_SCORE <= 10),
    RATING_CREATED_AT TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    RATING_UPDATED_AT TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (STORY_ID, USER_ID)
);

CREATE TABLE IF NOT EXISTS T_VIEWS (
    VIEW_ID UUID PRIMARY KEY,
    STORY_ID UUID NOT NULL REFERENCES T_STORIES(STORY_ID) ON DELETE CASCADE,
    USER_ID UUID NOT NULL,
    VIEW_CREATED_AT TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    VIEW_UPDATED_AT TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (STORY_ID, USER_ID)
);

CREATE TABLE IF NOT EXISTS T_FAVORITE_STORIES (
    FAVORITE_STORY_ID UUID PRIMARY KEY,
    STORY_ID UUID NOT NULL REFERENCES T_STORIES(STORY_ID) ON DELETE CASCADE,
    USER_ID UUID NOT NULL,
    FAVORITE_CREATED_AT TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FAVORITE_UPDATED_AT TIMESTAMP WITHOUT TIME ZONE,
    UNIQUE (STORY_ID, USER_ID)
);

