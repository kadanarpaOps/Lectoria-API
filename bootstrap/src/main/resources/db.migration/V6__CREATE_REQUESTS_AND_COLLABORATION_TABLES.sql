CREATE TABLE IF NOT EXISTS T_USER_REQUESTS (
    REQUEST_ID UUID PRIMARY KEY,
    REQUEST_TYPE VARCHAR(40) NOT NULL,
    REQUEST_STATUS VARCHAR(20) NOT NULL,
    SOURCE_USER_ID UUID NOT NULL,
    TARGET_USER_ID UUID,
    STORY_ID UUID,
    COAUTHOR_USER_ID UUID,
    CREATED_AT TIMESTAMP NOT NULL,
    RESOLVED_AT TIMESTAMP
);

CREATE INDEX IF NOT EXISTS IDX_USER_REQUESTS_TARGET_STATUS
    ON T_USER_REQUESTS (TARGET_USER_ID, REQUEST_STATUS, CREATED_AT DESC);
CREATE INDEX IF NOT EXISTS IDX_USER_REQUESTS_SOURCE
    ON T_USER_REQUESTS (SOURCE_USER_ID, CREATED_AT DESC);
CREATE INDEX IF NOT EXISTS IDX_USER_REQUESTS_TYPE_STATUS
    ON T_USER_REQUESTS (REQUEST_TYPE, REQUEST_STATUS, CREATED_AT DESC);
CREATE UNIQUE INDEX IF NOT EXISTS UQ_PENDING_COAUTHOR_REQUEST
    ON T_USER_REQUESTS (SOURCE_USER_ID, TARGET_USER_ID, STORY_ID, COAUTHOR_USER_ID)
    WHERE REQUEST_TYPE = 'COAUTHOR_REQUEST' AND REQUEST_STATUS = 'PENDING';

CREATE TABLE IF NOT EXISTS T_STORY_COAUTHORS (
    COAUTHOR_ID UUID PRIMARY KEY,
    STORY_ID UUID NOT NULL,
    USER_ID UUID NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL,
    CONSTRAINT UQ_STORY_COAUTHOR UNIQUE (STORY_ID, USER_ID)
);

CREATE INDEX IF NOT EXISTS IDX_STORY_COAUTHORS_USER
    ON T_STORY_COAUTHORS (USER_ID, CREATED_AT DESC);

CREATE TABLE IF NOT EXISTS T_CHAPTER_EDIT_LOCKS (
    CHAPTER_ID UUID PRIMARY KEY,
    USER_ID UUID NOT NULL,
    EXPIRES_AT TIMESTAMP NOT NULL
);

CREATE INDEX IF NOT EXISTS IDX_CHAPTER_LOCKS_EXPIRATION
    ON T_CHAPTER_EDIT_LOCKS (EXPIRES_AT);
